"""Firebase Admin persistence. Client authorization is enforced here and in routes."""
from __future__ import annotations

import asyncio
from datetime import datetime, timezone
from decimal import Decimal
from functools import lru_cache
import uuid

from fastapi import HTTPException
from firebase_admin import credentials, firestore, initialize_app
from google.cloud.firestore_v1.base_query import FieldFilter

from .config import get_settings
from .documents import document_store


@lru_cache
def firebase_app():
    settings = get_settings()
    credential = credentials.Certificate(settings.firebase_credentials) if settings.firebase_credentials else credentials.ApplicationDefault()
    return initialize_app(credential, {'projectId': settings.firebase_project_id}, name='claimelens')


def now():
    return datetime.now(timezone.utc).isoformat()


def can_access_claim(user, claim):
    if user.profile.role == 'client':
        return claim.get('client_id') == user.id
    if user.profile.role == 'claims_officer':
        return claim.get('assigned_to') == user.id
    return user.profile.role in {'supervisor', 'administrator'}


class FirebaseGateway:
    def __init__(self, request):
        self.settings = get_settings()
        self.app = firebase_app()
        self.db = firestore.client(self.app)
        self.user = getattr(request.state, 'current_user', None)

    def _user(self):
        if self.user is None:
            raise HTTPException(401, 'Authentication required.')
        return self.user

    async def profile(self, uid):
        snapshot = await asyncio.to_thread(self.db.collection('profiles').document(uid).get)
        return snapshot.to_dict() if snapshot.exists else None

    async def ensure_profile(self, uid, display_name, email):
        ref = self.db.collection('profiles').document(uid)
        @firestore.transactional
        def ensure(transaction):
            snapshot = ref.get(transaction=transaction)
            if snapshot.exists:
                return snapshot.to_dict()
            value = {'id': uid, 'display_name': display_name or email.split('@')[0], 'email': email, 'role': 'client', 'status': 'active', 'created_at': now()}
            transaction.set(ref, value)
            return value
        return await asyncio.to_thread(ensure, self.db.transaction())

    async def records(self, method, collection, *, token=None, service=False, params=None, json=None, prefer=None):
        """Small internal CRUD interface used by the processing pipeline.

        Filter expressions are generated by server code, never accepted from HTTP.
        Unprivileged requests are always scoped to their authenticated claim owner.
        """
        if collection not in {'claims', 'claim_documents', 'claim_extracted_fields', 'claim_processing_jobs', 'audit_events'}:
            raise ValueError('Unsupported collection')
        user = None if service else self._user()
        params = params or {}
        def run():
            query = self.db.collection(collection)
            for key, expression in params.items():
                if key in {'select', 'order', 'limit', 'or'}:
                    continue
                operator, value = expression.split('.', 1)
                if operator == 'eq':
                    query = query.where(filter=FieldFilter(key, '==', value))
                elif operator == 'in':
                    query = query.where(filter=FieldFilter(key, 'in', value.strip('()').split(',')))
                else:
                    raise ValueError('Unsupported internal filter')
            # Scope the database query before reading client documents.
            if user and collection == 'claims':
                if user.profile.role == 'client':
                    query = query.where(filter=FieldFilter('client_id', '==', user.id))
                elif user.profile.role == 'claims_officer':
                    query = query.where(filter=FieldFilter('assigned_to', '==', user.id))
            if user and collection != 'claims':
                claim_id = params.get('claim_id') or (json.get('claim_id') if isinstance(json, dict) else None)
                if isinstance(claim_id, str) and claim_id.startswith('eq.'):
                    claim_id = claim_id[3:]
                parent = self.db.collection('claims').document(claim_id).get() if claim_id else None
                if not parent or not parent.exists or not can_access_claim(user, parent.to_dict()):
                    raise HTTPException(404, 'Claim not found.')
            if method == 'POST':
                if user and collection not in {'claims', 'claim_documents', 'audit_events'}:
                    raise HTTPException(403, 'Operation not permitted.')
                items = json if isinstance(json, list) else [json]
                result=[]
                for item in items:
                    item = dict(item)
                    identifier = str(uuid.uuid4())
                    item.update(id=identifier, created_at=now())
                    if collection == 'claims':
                        if user and (user.profile.role != 'client' or item.get('client_id') != user.id):
                            raise HTTPException(403, 'Only clients can create their own claims.')
                        item.update(reference='CLM-'+datetime.now(timezone.utc).strftime('%Y%m%d')+'-'+identifier[:8].upper(), warning_count=0, claimed_amount=None, assigned_to=None)
                    if collection == 'claim_documents':
                        item.update(extraction_status='PENDING', include_in_total=False)
                    self.db.collection(collection).document(identifier).create(item)
                    result.append(item)
                return result
            rows = [s.to_dict() for s in query.stream()]
            if 'or' in params:
                term = params['or'].split('*')[1].lower()
                rows = [r for r in rows if any(term in str(r.get(k, '')).lower() for k in ('reference','patient_name','provider_name'))]
            if 'order' in params:
                key, direction = params['order'].split('.')
                rows.sort(key=lambda r: str(r.get(key, '')), reverse=direction == 'desc')
            if 'limit' in params:
                rows=rows[:int(params['limit'])]
            if method == 'GET':
                return rows
            if user and method != 'DELETE':
                raise HTTPException(403, 'Operation not permitted.')
            for row in rows:
                ref=self.db.collection(collection).document(row['id'])
                if method == 'PATCH':
                    ref.update(json)
                elif method == 'DELETE':
                    if user and (collection != 'claims' or row.get('status') != 'UPLOADED' or row.get('client_id') != user.id):
                        raise HTTPException(403, 'Operation not permitted.')
                    ref.delete()
                    if collection == 'claims':
                        for child in ('claim_documents','claim_extracted_fields','claim_processing_jobs','audit_events'):
                            for document in self.db.collection(child).where(filter=FieldFilter('claim_id','==',row['id'])).stream():
                                document.reference.delete()
                else:
                    raise ValueError('Unsupported method')
            return rows
        return await asyncio.to_thread(run)

    async def upload(self, path, content, content_type, token):
        if not path.startswith(self._user().id+'/'):
            raise HTTPException(403, 'Invalid document path.')
        await asyncio.to_thread(document_store().upload, path, content, content_type)

    async def download(self, path, *, service=True):
        return await asyncio.to_thread(document_store().download, path)

    async def delete_objects(self, paths, token):
        for path in paths:
            if not path.startswith(self._user().id+'/'):
                raise HTTPException(403, 'Invalid document path.')
            await asyncio.to_thread(document_store().delete, path)

    async def signed_url(self, path, token, expires_in=300):
        # Called only after the claim route has authorized access to its documents.
        return await asyncio.to_thread(document_store().signed_url, path, expires_in)

    async def acquire_processing(self, claim_id):
        user=self._user()
        ref=self.db.collection('claims').document(claim_id)
        @firestore.transactional
        def acquire(transaction):
            snapshot=ref.get(transaction=transaction)
            claim=snapshot.to_dict() if snapshot.exists else None
            if not claim or not can_access_claim(user, claim):
                raise HTTPException(404, 'Claim not found.')
            if claim['status'] not in {'UPLOADED','PROCESSING_FAILED'}:
                raise HTTPException(409, 'This claim is not available for processing.')
            transaction.update(ref, {'status':'PROCESSING'})
        await asyncio.to_thread(acquire,self.db.transaction())

    async def confirm(self, claim_id, payload):
        user=self._user()
        ref=self.db.collection('claims').document(claim_id)
        @firestore.transactional
        def confirm(transaction):
            snapshot=ref.get(transaction=transaction)
            claim=snapshot.to_dict() if snapshot.exists else None
            if not claim or claim.get('client_id') != user.id or user.profile.role != 'client':
                raise HTTPException(403, 'Only the claim owner can confirm this draft.')
            if claim['status'] != 'UPLOADED':
                raise HTTPException(409, 'This claim has already been submitted or is processing.')
            docs=list(self.db.collection('claim_documents').where(filter=FieldFilter('claim_id','==',claim_id)).stream(transaction=transaction))
            fields=list(self.db.collection('claim_extracted_fields').where(filter=FieldFilter('claim_id','==',claim_id)).stream(transaction=transaction))
            by_id={d.id:d for d in docs}
            field_ids={d.id:d for d in fields}
            if len({d.id for d in payload.documents}) != len(payload.documents) or set(by_id) != {d.id for d in payload.documents}:
                raise HTTPException(422,'Confirm each document exactly once.')
            updates=[]
            total=Decimal('0')
            currencies=set()
            for item in payload.documents:
                if item.include:
                    original=by_id[item.id].to_dict()
                    if original.get('duplicate_of') or item.amount is None or item.amount <= 0 or item.amount.as_tuple().exponent < -2 or not item.currency or len(item.currency) != 3:
                        raise HTTPException(422,'Included documents need a positive amount, a three-letter currency, and must not be duplicates.')
                    total+=item.amount
                    currencies.add(item.currency.upper())
                updates.append((by_id[item.id].reference,{'include_in_total':item.include,'confirmed_amount':str(item.amount) if item.include else None,'confirmed_currency':item.currency.upper() if item.include else None}))
            if total <= 0 or len(currencies) != 1:
                raise HTTPException(422,'Include at least one payable document; all amounts must use the same currency.')
            if len({str(f.id) for f in payload.fields}) != len(payload.fields):
                raise HTTPException(422,'Duplicate corrected fields.')
            for correction in payload.fields:
                if not correction.value.strip():
                    raise HTTPException(422,'Corrected values cannot be blank.')
                field=field_ids.get(str(correction.id))
                if not field:
                    raise HTTPException(422,'Corrected field does not belong to this claim.')
                updates.append((field.reference,{'normalized_value':correction.value.strip(),'extraction_method':'human_corrected','confidence':0}))
                audit=self.db.collection('audit_events').document()
                transaction.set(audit,{'id':audit.id,'claim_id':claim_id,'actor_id':user.id,'event_type':'FIELD_CORRECTED','created_at':now(),'metadata':{'previous_value':field.to_dict().get('normalized_value'),'corrected_value':correction.value.strip()}})
            for target,update in updates:
                transaction.update(target,update)
            transaction.update(ref,{'patient_name':payload.patient_name.strip(),'provider_name':payload.provider_name.strip(),'claimed_amount':str(total),'currency':next(iter(currencies)),'status':'REVIEW_REQUIRED'})
            audit=self.db.collection('audit_events').document()
            transaction.set(audit,{'id':audit.id,'claim_id':claim_id,'actor_id':user.id,'event_type':'CLAIM_CONFIRMED','created_at':now(),'metadata':{'total':str(total)}})
            return 'REVIEW_REQUIRED'
        return await asyncio.to_thread(confirm,self.db.transaction())
